export function getGuideArticle(slug: string): GuideArticle | undefined {
  return guideArticles.find((a) => a.slug === slug);
}

export function getAllGuideSlugs(): string[] {
  return guideArticles.map((a) => a.slug);
}

export function getRelatedGuideArticles(slug: string, limit = 3): GuideArticle[] {
  const article = getGuideArticle(slug);
  if (!article) return [];
  const related = article.relatedSlugs
    .map((s) => getGuideArticle(s))
    .filter((a): a is GuideArticle => Boolean(a));
  return related.slice(0, limit);
}
